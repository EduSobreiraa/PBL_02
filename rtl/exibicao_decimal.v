`timescale 1ns/1ps
// Converte o resultado em seis dígitos, mostra o sinal e indica valores fora da faixa.
module exibicao_decimal(input wire signed [22:0] value, input wire invalid, output wire overflow_exibicao,
    output wire [6:0] HEX0,HEX1,HEX2,HEX3,HEX4,HEX5);
    wire [22:0] modulo_sinalizado;
    wire [26:0] bcd_corrigido;
    wire [6:0] digito_nao_zero;
    wire [5:0] digitos_visiveis;
    wire estouro_negativo,fora_da_faixa,faixa_valida,traco_superior;
    // Separa o sinal e converte o valor absoluto para BCD.
    magnitude_decimal mag(.value(value),.magnitude(modulo_sinalizado));
    conversor_binario_bcd convert(.magnitude(modulo_sinalizado),.corrected(bcd_corrigido));
    or nonzero0(digito_nao_zero[0],bcd_corrigido[0],bcd_corrigido[1],bcd_corrigido[2],modulo_sinalizado[0]);
    or nonzero1(digito_nao_zero[1],bcd_corrigido[3],bcd_corrigido[4],bcd_corrigido[5],bcd_corrigido[6]);
    or nonzero2(digito_nao_zero[2],bcd_corrigido[7],bcd_corrigido[8],bcd_corrigido[9],bcd_corrigido[10]);
    or nonzero3(digito_nao_zero[3],bcd_corrigido[11],bcd_corrigido[12],bcd_corrigido[13],bcd_corrigido[14]);
    or nonzero4(digito_nao_zero[4],bcd_corrigido[15],bcd_corrigido[16],bcd_corrigido[17],bcd_corrigido[18]);
    or nonzero5(digito_nao_zero[5],bcd_corrigido[19],bcd_corrigido[20],bcd_corrigido[21],bcd_corrigido[22]);
    or nonzero6(digito_nao_zero[6],bcd_corrigido[23],bcd_corrigido[24],bcd_corrigido[25],bcd_corrigido[26]);
    and negative_range(estouro_negativo,value[22],digito_nao_zero[5]);
    or presentation_overflow(overflow_exibicao,digito_nao_zero[6],estouro_negativo);
    or out_of_range(fora_da_faixa,invalid,digito_nao_zero[6],estouro_negativo);
    not valid_range(faixa_valida,fora_da_faixa);
    and visible0(digitos_visiveis[0],1'b1,1'b1);
    or show1(digitos_visiveis[1],digito_nao_zero[1],digito_nao_zero[2],digito_nao_zero[3],digito_nao_zero[4],digito_nao_zero[5],digito_nao_zero[6]);
    or show2(digitos_visiveis[2],digito_nao_zero[2],digito_nao_zero[3],digito_nao_zero[4],digito_nao_zero[5],digito_nao_zero[6]);
    or show3(digitos_visiveis[3],digito_nao_zero[3],digito_nao_zero[4],digito_nao_zero[5],digito_nao_zero[6]);
    or show4(digitos_visiveis[4],digito_nao_zero[4],digito_nao_zero[5],digito_nao_zero[6]);
    or show5(digitos_visiveis[5],digito_nao_zero[5],digito_nao_zero[6]);
    or sign_or_error(traco_superior,fora_da_faixa,value[22]);
    wire [5:0] mostrar_digito;
    wire posicao_superior_normal;
    not positive_top(posicao_superior_normal,value[22]);
    // Dígitos sem valor à esquerda ficam apagados.
    and enabled0(mostrar_digito[0],digitos_visiveis[0],faixa_valida);
    posicao_decimal position0(.digit({bcd_corrigido[2:0],modulo_sinalizado[0]}),.show_digit(mostrar_digito[0]),.dash(fora_da_faixa),.segments(HEX0));
    and enabled1(mostrar_digito[1],digitos_visiveis[1],faixa_valida);
    posicao_decimal position1(.digit(bcd_corrigido[6:3]),.show_digit(mostrar_digito[1]),.dash(fora_da_faixa),.segments(HEX1));
    and enabled2(mostrar_digito[2],digitos_visiveis[2],faixa_valida);
    posicao_decimal position2(.digit(bcd_corrigido[10:7]),.show_digit(mostrar_digito[2]),.dash(fora_da_faixa),.segments(HEX2));
    and enabled3(mostrar_digito[3],digitos_visiveis[3],faixa_valida);
    posicao_decimal position3(.digit(bcd_corrigido[14:11]),.show_digit(mostrar_digito[3]),.dash(fora_da_faixa),.segments(HEX3));
    and enabled4(mostrar_digito[4],digitos_visiveis[4],faixa_valida);
    posicao_decimal position4(.digit(bcd_corrigido[18:15]),.show_digit(mostrar_digito[4]),.dash(fora_da_faixa),.segments(HEX4));
    and enabled5(mostrar_digito[5],digitos_visiveis[5],faixa_valida,posicao_superior_normal);
    posicao_decimal position5(.digit(bcd_corrigido[22:19]),.show_digit(mostrar_digito[5]),.dash(traco_superior),.segments(HEX5));
endmodule
// Obtém o valor absoluto sem alterar o número de entrada.
module magnitude_decimal(input wire [22:0] value,output wire [22:0] magnitude);
    wire [22:0] bits_invertidos;
    wire [23:0] vai_um;
    xor toggle0(bits_invertidos[0],value[0],value[22]);
    xor sum0(magnitude[0],bits_invertidos[0],value[22]);
    and c0(vai_um[1],bits_invertidos[0],value[22]);
    xor toggle1(bits_invertidos[1],value[1],value[22]);
    xor sum1(magnitude[1],bits_invertidos[1],vai_um[1]);
    and c1(vai_um[2],bits_invertidos[1],vai_um[1]);
    xor toggle2(bits_invertidos[2],value[2],value[22]);
    xor sum2(magnitude[2],bits_invertidos[2],vai_um[2]);
    and c2(vai_um[3],bits_invertidos[2],vai_um[2]);
    xor toggle3(bits_invertidos[3],value[3],value[22]);
    xor sum3(magnitude[3],bits_invertidos[3],vai_um[3]);
    and c3(vai_um[4],bits_invertidos[3],vai_um[3]);
    xor toggle4(bits_invertidos[4],value[4],value[22]);
    xor sum4(magnitude[4],bits_invertidos[4],vai_um[4]);
    and c4(vai_um[5],bits_invertidos[4],vai_um[4]);
    xor toggle5(bits_invertidos[5],value[5],value[22]);
    xor sum5(magnitude[5],bits_invertidos[5],vai_um[5]);
    and c5(vai_um[6],bits_invertidos[5],vai_um[5]);
    xor toggle6(bits_invertidos[6],value[6],value[22]);
    xor sum6(magnitude[6],bits_invertidos[6],vai_um[6]);
    and c6(vai_um[7],bits_invertidos[6],vai_um[6]);
    xor toggle7(bits_invertidos[7],value[7],value[22]);
    xor sum7(magnitude[7],bits_invertidos[7],vai_um[7]);
    and c7(vai_um[8],bits_invertidos[7],vai_um[7]);
    xor toggle8(bits_invertidos[8],value[8],value[22]);
    xor sum8(magnitude[8],bits_invertidos[8],vai_um[8]);
    and c8(vai_um[9],bits_invertidos[8],vai_um[8]);
    xor toggle9(bits_invertidos[9],value[9],value[22]);
    xor sum9(magnitude[9],bits_invertidos[9],vai_um[9]);
    and c9(vai_um[10],bits_invertidos[9],vai_um[9]);
    xor toggle10(bits_invertidos[10],value[10],value[22]);
    xor sum10(magnitude[10],bits_invertidos[10],vai_um[10]);
    and c10(vai_um[11],bits_invertidos[10],vai_um[10]);
    xor toggle11(bits_invertidos[11],value[11],value[22]);
    xor sum11(magnitude[11],bits_invertidos[11],vai_um[11]);
    and c11(vai_um[12],bits_invertidos[11],vai_um[11]);
    xor toggle12(bits_invertidos[12],value[12],value[22]);
    xor sum12(magnitude[12],bits_invertidos[12],vai_um[12]);
    and c12(vai_um[13],bits_invertidos[12],vai_um[12]);
    xor toggle13(bits_invertidos[13],value[13],value[22]);
    xor sum13(magnitude[13],bits_invertidos[13],vai_um[13]);
    and c13(vai_um[14],bits_invertidos[13],vai_um[13]);
    xor toggle14(bits_invertidos[14],value[14],value[22]);
    xor sum14(magnitude[14],bits_invertidos[14],vai_um[14]);
    and c14(vai_um[15],bits_invertidos[14],vai_um[14]);
    xor toggle15(bits_invertidos[15],value[15],value[22]);
    xor sum15(magnitude[15],bits_invertidos[15],vai_um[15]);
    and c15(vai_um[16],bits_invertidos[15],vai_um[15]);
    xor toggle16(bits_invertidos[16],value[16],value[22]);
    xor sum16(magnitude[16],bits_invertidos[16],vai_um[16]);
    and c16(vai_um[17],bits_invertidos[16],vai_um[16]);
    xor toggle17(bits_invertidos[17],value[17],value[22]);
    xor sum17(magnitude[17],bits_invertidos[17],vai_um[17]);
    and c17(vai_um[18],bits_invertidos[17],vai_um[17]);
    xor toggle18(bits_invertidos[18],value[18],value[22]);
    xor sum18(magnitude[18],bits_invertidos[18],vai_um[18]);
    and c18(vai_um[19],bits_invertidos[18],vai_um[18]);
    xor toggle19(bits_invertidos[19],value[19],value[22]);
    xor sum19(magnitude[19],bits_invertidos[19],vai_um[19]);
    and c19(vai_um[20],bits_invertidos[19],vai_um[19]);
    xor toggle20(bits_invertidos[20],value[20],value[22]);
    xor sum20(magnitude[20],bits_invertidos[20],vai_um[20]);
    and c20(vai_um[21],bits_invertidos[20],vai_um[20]);
    xor toggle21(bits_invertidos[21],value[21],value[22]);
    xor sum21(magnitude[21],bits_invertidos[21],vai_um[21]);
    and c21(vai_um[22],bits_invertidos[21],vai_um[21]);
    xor toggle22(bits_invertidos[22],value[22],value[22]);
    xor sum22(magnitude[22],bits_invertidos[22],vai_um[22]);
    and c22(vai_um[23],bits_invertidos[22],vai_um[22]);
endmodule
// Converte o valor binário em dígitos BCD por etapas combinacionais.
