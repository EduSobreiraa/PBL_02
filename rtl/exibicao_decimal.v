// Corrige os dígitos BCD atuais e acrescenta o próximo bit do número.
module etapa_conversao_bcd(input wire [27:0] previous,output wire [26:0] corrected);
    wire bit_milhoes_nao_utilizado;
    soma_tres_bcd d0(.digit(previous[3:0]),.corrected(corrected[3:0]));
    soma_tres_bcd d1(.digit(previous[7:4]),.corrected(corrected[7:4]));
    soma_tres_bcd d2(.digit(previous[11:8]),.corrected(corrected[11:8]));
    soma_tres_bcd d3(.digit(previous[15:12]),.corrected(corrected[15:12]));
    soma_tres_bcd d4(.digit(previous[19:16]),.corrected(corrected[19:16]));
    soma_tres_bcd d5(.digit(previous[23:20]),.corrected(corrected[23:20]));
    soma_tres_bcd d6(.digit(previous[27:24]),.corrected({bit_milhoes_nao_utilizado,corrected[26:24]}));
endmodule
// Ajusta um dígito BCD quando o valor passa de quatro.
module soma_tres_bcd(input wire [3:0] digit,output wire [3:0] corrected);
    wire [3:0] n;
    wire [15:0] m;
    // As portas seguintes somam três aos dígitos BCD de 5 a 9.
    not n0(n[0],digit[0]);
    not n1(n[1],digit[1]);
    not n2(n[2],digit[2]);
    not n3(n[3],digit[3]);
    and m0(m[0],n[0],n[1],n[2],n[3]);
    and m1(m[1],digit[0],n[1],n[2],n[3]);
    and m2(m[2],n[0],digit[1],n[2],n[3]);
    and m3(m[3],digit[0],digit[1],n[2],n[3]);
    and m4(m[4],n[0],n[1],digit[2],n[3]);
    and m5(m[5],digit[0],n[1],digit[2],n[3]);
    and m6(m[6],n[0],digit[1],digit[2],n[3]);
    and m7(m[7],digit[0],digit[1],digit[2],n[3]);
    and m8(m[8],n[0],n[1],n[2],digit[3]);
    and m9(m[9],digit[0],n[1],n[2],digit[3]);
    and m10(m[10],n[0],digit[1],n[2],digit[3]);
    and m11(m[11],digit[0],digit[1],n[2],digit[3]);
    and m12(m[12],n[0],n[1],digit[2],digit[3]);
    and m13(m[13],digit[0],n[1],digit[2],digit[3]);
    and m14(m[14],n[0],digit[1],digit[2],digit[3]);
    and m15(m[15],digit[0],digit[1],digit[2],digit[3]);
    or out0(corrected[0],m[1],m[3],m[6],m[8],m[10],m[12],m[14]);
    or out1(corrected[1],m[2],m[3],m[7],m[8],m[11],m[12],m[15]);
    or out2(corrected[2],m[4],m[9],m[10],m[11],m[12]);
    or out3(corrected[3],m[5],m[6],m[7],m[8],m[9],m[10],m[11],m[12]);
endmodule
// Escolhe os segmentos acesos para representar um dígito decimal.
module decodificador_bcd_segmentos(input wire [3:0] digit,output wire [6:0] segments);
    wire [3:0] n;
    wire [9:0] m;
    // Cada termo m representa um dígito de 0 a 9.
    not n0(n[0],digit[0]);
    not n1(n[1],digit[1]);
    not n2(n[2],digit[2]);
    not n3(n[3],digit[3]);
    and m0(m[0],n[0],n[1],n[2],n[3]);
    and m1(m[1],digit[0],n[1],n[2],n[3]);
    and m2(m[2],n[0],digit[1],n[2],n[3]);
    and m3(m[3],digit[0],digit[1],n[2],n[3]);
    and m4(m[4],n[0],n[1],digit[2],n[3]);
    and m5(m[5],digit[0],n[1],digit[2],n[3]);
    and m6(m[6],n[0],digit[1],digit[2],n[3]);
    and m7(m[7],digit[0],digit[1],digit[2],n[3]);
    and m8(m[8],n[0],n[1],n[2],digit[3]);
    and m9(m[9],digit[0],n[1],n[2],digit[3]);
    nor seg0(segments[0],m[0],m[2],m[3],m[5],m[6],m[7],m[8],m[9]);
    nor seg1(segments[1],m[0],m[1],m[2],m[3],m[4],m[7],m[8],m[9]);
    nor seg2(segments[2],m[0],m[1],m[3],m[4],m[5],m[6],m[7],m[8],m[9]);
    nor seg3(segments[3],m[0],m[2],m[3],m[5],m[6],m[8],m[9]);
    nor seg4(segments[4],m[0],m[2],m[6],m[8]);
    nor seg5(segments[5],m[0],m[4],m[5],m[6],m[8],m[9]);
    nor seg6(segments[6],m[2],m[3],m[4],m[5],m[6],m[8],m[9]);
endmodule
// Mostra um dígito, um traço ou deixa a posição apagada.
module posicao_decimal(input wire [3:0] digit,input wire show_digit,dash,output wire [6:0] segments);
    wire [6:0] segmentos_decodificados,segmentos_ativos,digitos_visiveis;
    decodificador_bcd_segmentos decoder(.digit(digit),.segments(segmentos_decodificados));
    not invert0(segmentos_ativos[0],segmentos_decodificados[0]);
    and show0(digitos_visiveis[0],segmentos_ativos[0],show_digit);
    not out0(segments[0],digitos_visiveis[0]);
    not invert1(segmentos_ativos[1],segmentos_decodificados[1]);
    and show1(digitos_visiveis[1],segmentos_ativos[1],show_digit);
    not out1(segments[1],digitos_visiveis[1]);
    not invert2(segmentos_ativos[2],segmentos_decodificados[2]);
    and show2(digitos_visiveis[2],segmentos_ativos[2],show_digit);
    not out2(segments[2],digitos_visiveis[2]);
    not invert3(segmentos_ativos[3],segmentos_decodificados[3]);
    and show3(digitos_visiveis[3],segmentos_ativos[3],show_digit);
    not out3(segments[3],digitos_visiveis[3]);
    not invert4(segmentos_ativos[4],segmentos_decodificados[4]);
    and show4(digitos_visiveis[4],segmentos_ativos[4],show_digit);
    not out4(segments[4],digitos_visiveis[4]);
    not invert5(segmentos_ativos[5],segmentos_decodificados[5]);
    and show5(digitos_visiveis[5],segmentos_ativos[5],show_digit);
    not out5(segments[5],digitos_visiveis[5]);
    not invert6(segmentos_ativos[6],segmentos_decodificados[6]);
    and show6(digitos_visiveis[6],segmentos_ativos[6],show_digit);
    nor out6(segments[6],digitos_visiveis[6],dash);
endmodule
