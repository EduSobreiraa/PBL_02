module display_status_pbl03(input busy, input done, input error_a_zero_f1, input error_vertex_f1, input error_a_zero_f2, input error_vertex_f2, output [9:0] LEDR, output [6:0] HEX0, output [6:0] HEX1, output [6:0] HEX2, output [6:0] HEX3, output [6:0] HEX4, output [6:0] HEX5);
wire sem_f1;
wire sem_vertex_f1;
wire sem_a_zero_f2;
wire mensagem_f1;
wire mensagem_v1;
wire mensagem_f2;
wire mensagem_v2;
wire mostrar;
wire funcao;
wire vertice;
wire indice1;
wire indice2;
wire [2:0] glifo_e;
wire [2:0] glifo_r;
wire [2:0] glifo_tipo;
wire [2:0] glifo_indice;
and (LEDR[0], busy, 1'b1);
and (LEDR[1], done, 1'b1);
or (LEDR[2], error_a_zero_f1, error_vertex_f1);
or (LEDR[3], error_a_zero_f2, error_vertex_f2);
and (LEDR[4], 1'b0, 1'b0);
and (LEDR[5], 1'b0, 1'b0);
and (LEDR[6], 1'b0, 1'b0);
and (LEDR[7], 1'b0, 1'b0);
and (LEDR[8], 1'b0, 1'b0);
and (LEDR[9], 1'b0, 1'b0);
not (sem_f1, error_a_zero_f1);
nor (sem_vertex_f1, error_a_zero_f1, error_vertex_f1);
nor (sem_a_zero_f2, error_a_zero_f1, error_vertex_f1, error_a_zero_f2);
and (mensagem_f1, done, error_a_zero_f1);
and (mensagem_v1, done, sem_f1, error_vertex_f1);
and (mensagem_f2, done, sem_vertex_f1, error_a_zero_f2);
and (mensagem_v2, done, sem_a_zero_f2, error_vertex_f2);
or (mostrar, mensagem_f1, mensagem_v1, mensagem_f2, mensagem_v2);
or (funcao, mensagem_f1, mensagem_f2);
or (vertice, mensagem_v1, mensagem_v2);
or (indice1, mensagem_f1, mensagem_v1);
or (indice2, mensagem_f2, mensagem_v2);
and (glifo_e[0], mostrar, 1'b1);
and (glifo_e[1], 1'b0, 1'b0);
and (glifo_e[2], 1'b0, 1'b0);
and (glifo_r[0], 1'b0, 1'b0);
and (glifo_r[1], mostrar, 1'b1);
and (glifo_r[2], 1'b0, 1'b0);
and (glifo_tipo[0], funcao, 1'b1);
and (glifo_tipo[1], funcao, 1'b1);
and (glifo_tipo[2], vertice, 1'b1);
and (glifo_indice[0], indice1, 1'b1);
and (glifo_indice[1], indice2, 1'b1);
and (glifo_indice[2], mostrar, 1'b1);
decodificador_glifo_7seg_pbl03 hex5 (.glifo(glifo_e), .segmentos(HEX5));
decodificador_glifo_7seg_pbl03 hex4 (.glifo(glifo_r), .segmentos(HEX4));
decodificador_glifo_7seg_pbl03 hex3 (.glifo(glifo_r), .segmentos(HEX3));
decodificador_glifo_7seg_pbl03 hex2 (.glifo(3'b000), .segmentos(HEX2));
decodificador_glifo_7seg_pbl03 hex1 (.glifo(glifo_tipo), .segmentos(HEX1));
decodificador_glifo_7seg_pbl03 hex0 (.glifo(glifo_indice), .segmentos(HEX0));
endmodule
