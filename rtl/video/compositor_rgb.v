module compositor_rgb(input video_on, input eixo_horizontal, input eixo_vertical, input processing_done, input f1_hit, input f1_derivada_hit, input f2_hit, input f2_derivada_hit, output [3:0] red, output [3:0] green, output [3:0] blue);
wire pixel_f1;
wire pixel_f1_derivada;
wire pixel_f2;
wire pixel_f2_derivada;
wire sem_f1;
wire sem_f1_derivada;
wire sem_f2;
wire sem_curva;
wire eixo;
wire pixel_eixo;
wire canal_red;
wire canal_green;
wire canal_blue;
and (pixel_f1, processing_done, f1_hit);
not (sem_f1, pixel_f1);
and (pixel_f1_derivada, processing_done, f1_derivada_hit, sem_f1);
nor (sem_f1_derivada, pixel_f1, pixel_f1_derivada);
and (pixel_f2, processing_done, f2_hit, sem_f1_derivada);
nor (sem_f2, pixel_f1, pixel_f1_derivada, pixel_f2);
and (pixel_f2_derivada, processing_done, f2_derivada_hit, sem_f2);
nor (sem_curva, pixel_f1, pixel_f1_derivada, pixel_f2, pixel_f2_derivada);
or (eixo, eixo_horizontal, eixo_vertical);
and (pixel_eixo, eixo, sem_curva);
or (canal_red, pixel_f2, pixel_f2_derivada, pixel_eixo);
or (canal_green, pixel_f1_derivada, pixel_f2_derivada, pixel_eixo);
or (canal_blue, pixel_f1, pixel_f1_derivada, pixel_eixo);
and (red[0], video_on, canal_red);
and (red[1], video_on, canal_red);
and (red[2], video_on, canal_red);
and (red[3], video_on, canal_red);
and (green[0], video_on, canal_green);
and (green[1], video_on, canal_green);
and (green[2], video_on, canal_green);
and (green[3], video_on, canal_green);
and (blue[0], video_on, canal_blue);
and (blue[1], video_on, canal_blue);
and (blue[2], video_on, canal_blue);
and (blue[3], video_on, canal_blue);
endmodule
