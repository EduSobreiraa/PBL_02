module quadratic_roots(input wire signed [7:0] a,b,c,
    output wire signed [17:0] delta, output wire signed [8:0] x1,x2, output wire domain_error);
    wire signed [15:0] b_square,ac;
    wire signed [17:0] b_extended,ac_four;
    wire a_zero,valid,delta_nonnegative;
    wire [16:0] radicand;
    wire [8:0] square_root;
    wire [9:0] square_remainder,b_extended10,negative_b,s_extended,nplus,nminus;
    wire [7:0] a_magnitude;
    mul_s8_s8 mb(.lhs(b),.rhs(b),.product(b_square));
    mul_s8_s8 mac(.lhs(a),.rhs(c),.product(ac));
    assign b_extended = {3'b000,b_square[14:0]};
    assign ac_four = {ac,2'b00};
    sub18 discriminant(.lhs(b_extended),.rhs(ac_four),.difference(delta));
    nor az(a_zero,a[0],a[1],a[2],a[3],a[4],a[5],a[6],a[7]);
    or err(domain_error,a_zero,delta[17]);
    not v(valid,domain_error);
    not dn(delta_nonnegative,delta[17]);
    and rad0(radicand[0],delta[0],delta_nonnegative);
    and rad1(radicand[1],delta[1],delta_nonnegative);
    and rad2(radicand[2],delta[2],delta_nonnegative);
    and rad3(radicand[3],delta[3],delta_nonnegative);
    and rad4(radicand[4],delta[4],delta_nonnegative);
    and rad5(radicand[5],delta[5],delta_nonnegative);
    and rad6(radicand[6],delta[6],delta_nonnegative);
    and rad7(radicand[7],delta[7],delta_nonnegative);
    and rad8(radicand[8],delta[8],delta_nonnegative);
    and rad9(radicand[9],delta[9],delta_nonnegative);
    and rad10(radicand[10],delta[10],delta_nonnegative);
    and rad11(radicand[11],delta[11],delta_nonnegative);
    and rad12(radicand[12],delta[12],delta_nonnegative);
    and rad13(radicand[13],delta[13],delta_nonnegative);
    and rad14(radicand[14],delta[14],delta_nonnegative);
    and rad15(radicand[15],delta[15],delta_nonnegative);
    and rad16(radicand[16],delta[16],delta_nonnegative);
    sqrt_u17 root(.radicand(radicand),.root(square_root),.remainder(square_remainder));
    assign b_extended10 = {{2{b[7]}},b};
    assign s_extended = {1'b0,square_root};
    roots_condneg10 nb(.value(b_extended10),.negate(1'b1),.result(negative_b));
    roots_addsub10 np(.lhs(negative_b),.rhs(s_extended),.subtract(1'b0),.result(nplus));
    roots_addsub10 nm(.lhs(negative_b),.rhs(s_extended),.subtract(1'b1),.result(nminus));
    roots_condneg8 amag(.value(a),.negate(a[7]),.result(a_magnitude));
    roots_branch plus_branch(.numerator(nplus),.magnitude_a(a_magnitude),.sign_a(a[7]),.square_remainder(square_remainder),.plus_branch(1'b1),.valid(valid),.result(x1));
    roots_branch minus_branch(.numerator(nminus),.magnitude_a(a_magnitude),.sign_a(a[7]),.square_remainder(square_remainder),.plus_branch(1'b0),.valid(valid),.result(x2));
endmodule

module roots_branch(input wire [9:0] numerator, input wire [7:0] magnitude_a,
    input wire sign_a, input wire [9:0] square_remainder, input wire plus_branch,valid,
    output wire [8:0] result);
    wire [9:0] magnitude_n;
    wire [8:0] quotient,base,rounded,signed_result;
    wire [7:0] remainder;
    wire divide_zero,n_nonzero,n_positive,minus_branch,correction_plus,correction_minus,correction;
    wire remainder_nonzero,square_exact,round_condition,up,result_sign;
    roots_condneg10 magnitude(.value(numerator),.negate(numerator[9]),.result(magnitude_n));
    // |N|<=413: magnitude_n[9] is provably zero.
    divide_u9_u8 divide(.dividend(magnitude_n[8:0]),.divisor(magnitude_a),.quotient(quotient),.remainder(remainder),.divide_by_zero(divide_zero));
    or nn(n_nonzero,numerator[0],numerator[1],numerator[2],numerator[3],numerator[4],numerator[5],numerator[6],numerator[7],numerator[8]);
    wire n_nonnegative;
    not nns(n_nonnegative,numerator[9]);
    and np(n_positive,n_nonnegative,n_nonzero);
    not mb(minus_branch,plus_branch);
    and cp(correction_plus,plus_branch,n_positive);
    and cm(correction_minus,minus_branch,numerator[9]);
    or co(correction,correction_plus,correction_minus);
    or rn(remainder_nonzero,remainder[0],remainder[1],remainder[2],remainder[3],remainder[4],remainder[5],remainder[6],remainder[7]);
    nor se(square_exact,square_remainder[0],square_remainder[1],square_remainder[2],square_remainder[3],square_remainder[4],square_remainder[5],square_remainder[6],square_remainder[7],square_remainder[8],square_remainder[9]);
    or rc(round_condition,remainder_nonzero,square_exact,correction);
    and u(up,quotient[0],round_condition);
    assign base = {1'b0,quotient[8:1]};
    roots_increment9 rounding(.value(base),.increment(up),.result(rounded));
    xor rs(result_sign,numerator[9],sign_a);
    roots_condneg9 restore_sign(.value(rounded),.negate(result_sign),.result(signed_result));
    and mask0(result[0],signed_result[0],valid);
    and mask1(result[1],signed_result[1],valid);
    and mask2(result[2],signed_result[2],valid);
    and mask3(result[3],signed_result[3],valid);
    and mask4(result[4],signed_result[4],valid);
    and mask5(result[5],signed_result[5],valid);
    and mask6(result[6],signed_result[6],valid);
    and mask7(result[7],signed_result[7],valid);
    and mask8(result[8],signed_result[8],valid);
endmodule
