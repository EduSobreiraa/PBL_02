module decimal_display(input wire signed [22:0] value, input wire invalid,
    output wire [6:0] HEX0,HEX1,HEX2,HEX3,HEX4,HEX5);
    wire [22:0] magnitude;
    wire [27:0] bcd;
    wire [6:0] digit_nonzero;
    wire [5:0] visible;
    wire negative_overflow,bad,good,top_dash;
    decimal_magnitude mag(.value(value),.magnitude(magnitude));
    decimal_double_dabble convert(.magnitude(magnitude),.bcd(bcd));
    or nonzero0(digit_nonzero[0],bcd[0],bcd[1],bcd[2],bcd[3]);
    or nonzero1(digit_nonzero[1],bcd[4],bcd[5],bcd[6],bcd[7]);
    or nonzero2(digit_nonzero[2],bcd[8],bcd[9],bcd[10],bcd[11]);
    or nonzero3(digit_nonzero[3],bcd[12],bcd[13],bcd[14],bcd[15]);
    or nonzero4(digit_nonzero[4],bcd[16],bcd[17],bcd[18],bcd[19]);
    or nonzero5(digit_nonzero[5],bcd[20],bcd[21],bcd[22],bcd[23]);
    or nonzero6(digit_nonzero[6],bcd[24],bcd[25],bcd[26],bcd[27]);
    and negative_range(negative_overflow,value[22],digit_nonzero[5]);
    or out_of_range(bad,invalid,digit_nonzero[6],negative_overflow);
    not valid_range(good,bad);
    assign visible[0] = 1'b1;
    or show1(visible[1],digit_nonzero[1],digit_nonzero[2],digit_nonzero[3],digit_nonzero[4],digit_nonzero[5],digit_nonzero[6]);
    or show2(visible[2],digit_nonzero[2],digit_nonzero[3],digit_nonzero[4],digit_nonzero[5],digit_nonzero[6]);
    or show3(visible[3],digit_nonzero[3],digit_nonzero[4],digit_nonzero[5],digit_nonzero[6]);
    or show4(visible[4],digit_nonzero[4],digit_nonzero[5],digit_nonzero[6]);
    or show5(visible[5],digit_nonzero[5],digit_nonzero[6]);
    or sign_or_error(top_dash,bad,value[22]);
    wire [5:0] show;
    wire top_normal;
    not positive_top(top_normal,value[22]);
    and enabled0(show[0],visible[0],good);
    decimal_position position0(.digit(bcd[3:0]),.show_digit(show[0]),.dash(bad),.segments(HEX0));
    and enabled1(show[1],visible[1],good);
    decimal_position position1(.digit(bcd[7:4]),.show_digit(show[1]),.dash(bad),.segments(HEX1));
    and enabled2(show[2],visible[2],good);
    decimal_position position2(.digit(bcd[11:8]),.show_digit(show[2]),.dash(bad),.segments(HEX2));
    and enabled3(show[3],visible[3],good);
    decimal_position position3(.digit(bcd[15:12]),.show_digit(show[3]),.dash(bad),.segments(HEX3));
    and enabled4(show[4],visible[4],good);
    decimal_position position4(.digit(bcd[19:16]),.show_digit(show[4]),.dash(bad),.segments(HEX4));
    and enabled5(show[5],visible[5],good,top_normal);
    decimal_position position5(.digit(bcd[23:20]),.show_digit(show[5]),.dash(top_dash),.segments(HEX5));
endmodule
module decimal_magnitude(input wire [22:0] value,output wire [22:0] magnitude);
    wire [22:0] toggled;
    wire [23:0] carry;
    assign carry[0] = value[22];
    xor toggle0(toggled[0],value[0],value[22]);
    xor sum0(magnitude[0],toggled[0],carry[0]);
    and c0(carry[1],toggled[0],carry[0]);
    xor toggle1(toggled[1],value[1],value[22]);
    xor sum1(magnitude[1],toggled[1],carry[1]);
    and c1(carry[2],toggled[1],carry[1]);
    xor toggle2(toggled[2],value[2],value[22]);
    xor sum2(magnitude[2],toggled[2],carry[2]);
    and c2(carry[3],toggled[2],carry[2]);
    xor toggle3(toggled[3],value[3],value[22]);
    xor sum3(magnitude[3],toggled[3],carry[3]);
    and c3(carry[4],toggled[3],carry[3]);
    xor toggle4(toggled[4],value[4],value[22]);
    xor sum4(magnitude[4],toggled[4],carry[4]);
    and c4(carry[5],toggled[4],carry[4]);
    xor toggle5(toggled[5],value[5],value[22]);
    xor sum5(magnitude[5],toggled[5],carry[5]);
    and c5(carry[6],toggled[5],carry[5]);
    xor toggle6(toggled[6],value[6],value[22]);
    xor sum6(magnitude[6],toggled[6],carry[6]);
    and c6(carry[7],toggled[6],carry[6]);
    xor toggle7(toggled[7],value[7],value[22]);
    xor sum7(magnitude[7],toggled[7],carry[7]);
    and c7(carry[8],toggled[7],carry[7]);
    xor toggle8(toggled[8],value[8],value[22]);
    xor sum8(magnitude[8],toggled[8],carry[8]);
    and c8(carry[9],toggled[8],carry[8]);
    xor toggle9(toggled[9],value[9],value[22]);
    xor sum9(magnitude[9],toggled[9],carry[9]);
    and c9(carry[10],toggled[9],carry[9]);
    xor toggle10(toggled[10],value[10],value[22]);
    xor sum10(magnitude[10],toggled[10],carry[10]);
    and c10(carry[11],toggled[10],carry[10]);
    xor toggle11(toggled[11],value[11],value[22]);
    xor sum11(magnitude[11],toggled[11],carry[11]);
    and c11(carry[12],toggled[11],carry[11]);
    xor toggle12(toggled[12],value[12],value[22]);
    xor sum12(magnitude[12],toggled[12],carry[12]);
    and c12(carry[13],toggled[12],carry[12]);
    xor toggle13(toggled[13],value[13],value[22]);
    xor sum13(magnitude[13],toggled[13],carry[13]);
    and c13(carry[14],toggled[13],carry[13]);
    xor toggle14(toggled[14],value[14],value[22]);
    xor sum14(magnitude[14],toggled[14],carry[14]);
    and c14(carry[15],toggled[14],carry[14]);
    xor toggle15(toggled[15],value[15],value[22]);
    xor sum15(magnitude[15],toggled[15],carry[15]);
    and c15(carry[16],toggled[15],carry[15]);
    xor toggle16(toggled[16],value[16],value[22]);
    xor sum16(magnitude[16],toggled[16],carry[16]);
    and c16(carry[17],toggled[16],carry[16]);
    xor toggle17(toggled[17],value[17],value[22]);
    xor sum17(magnitude[17],toggled[17],carry[17]);
    and c17(carry[18],toggled[17],carry[17]);
    xor toggle18(toggled[18],value[18],value[22]);
    xor sum18(magnitude[18],toggled[18],carry[18]);
    and c18(carry[19],toggled[18],carry[18]);
    xor toggle19(toggled[19],value[19],value[22]);
    xor sum19(magnitude[19],toggled[19],carry[19]);
    and c19(carry[20],toggled[19],carry[19]);
    xor toggle20(toggled[20],value[20],value[22]);
    xor sum20(magnitude[20],toggled[20],carry[20]);
    and c20(carry[21],toggled[20],carry[20]);
    xor toggle21(toggled[21],value[21],value[22]);
    xor sum21(magnitude[21],toggled[21],carry[21]);
    and c21(carry[22],toggled[21],carry[21]);
    xor toggle22(toggled[22],value[22],value[22]);
    xor sum22(magnitude[22],toggled[22],carry[22]);
    and c22(carry[23],toggled[22],carry[22]);
endmodule
module decimal_double_dabble(input wire [22:0] magnitude,output wire [27:0] bcd);
    wire [27:0] stage0;
    wire [27:0] stage1;
    wire [27:0] stage2;
    wire [27:0] stage3;
    wire [27:0] stage4;
    wire [27:0] stage5;
    wire [27:0] stage6;
    wire [27:0] stage7;
    wire [27:0] stage8;
    wire [27:0] stage9;
    wire [27:0] stage10;
    wire [27:0] stage11;
    wire [27:0] stage12;
    wire [27:0] stage13;
    wire [27:0] stage14;
    wire [27:0] stage15;
    wire [27:0] stage16;
    wire [27:0] stage17;
    wire [27:0] stage18;
    wire [27:0] stage19;
    wire [27:0] stage20;
    wire [27:0] stage21;
    wire [27:0] stage22;
    wire [27:0] stage23;
    assign stage0 = 28'b0;
    decimal_dabble_stage s0(.previous(stage0),.next_bit(magnitude[22]),.result(stage1));
    decimal_dabble_stage s1(.previous(stage1),.next_bit(magnitude[21]),.result(stage2));
    decimal_dabble_stage s2(.previous(stage2),.next_bit(magnitude[20]),.result(stage3));
    decimal_dabble_stage s3(.previous(stage3),.next_bit(magnitude[19]),.result(stage4));
    decimal_dabble_stage s4(.previous(stage4),.next_bit(magnitude[18]),.result(stage5));
    decimal_dabble_stage s5(.previous(stage5),.next_bit(magnitude[17]),.result(stage6));
    decimal_dabble_stage s6(.previous(stage6),.next_bit(magnitude[16]),.result(stage7));
    decimal_dabble_stage s7(.previous(stage7),.next_bit(magnitude[15]),.result(stage8));
    decimal_dabble_stage s8(.previous(stage8),.next_bit(magnitude[14]),.result(stage9));
    decimal_dabble_stage s9(.previous(stage9),.next_bit(magnitude[13]),.result(stage10));
    decimal_dabble_stage s10(.previous(stage10),.next_bit(magnitude[12]),.result(stage11));
    decimal_dabble_stage s11(.previous(stage11),.next_bit(magnitude[11]),.result(stage12));
    decimal_dabble_stage s12(.previous(stage12),.next_bit(magnitude[10]),.result(stage13));
    decimal_dabble_stage s13(.previous(stage13),.next_bit(magnitude[9]),.result(stage14));
    decimal_dabble_stage s14(.previous(stage14),.next_bit(magnitude[8]),.result(stage15));
    decimal_dabble_stage s15(.previous(stage15),.next_bit(magnitude[7]),.result(stage16));
    decimal_dabble_stage s16(.previous(stage16),.next_bit(magnitude[6]),.result(stage17));
    decimal_dabble_stage s17(.previous(stage17),.next_bit(magnitude[5]),.result(stage18));
    decimal_dabble_stage s18(.previous(stage18),.next_bit(magnitude[4]),.result(stage19));
    decimal_dabble_stage s19(.previous(stage19),.next_bit(magnitude[3]),.result(stage20));
    decimal_dabble_stage s20(.previous(stage20),.next_bit(magnitude[2]),.result(stage21));
    decimal_dabble_stage s21(.previous(stage21),.next_bit(magnitude[1]),.result(stage22));
    decimal_dabble_stage s22(.previous(stage22),.next_bit(magnitude[0]),.result(stage23));
    assign bcd = stage23;
endmodule
module decimal_dabble_stage(input wire [27:0] previous,input wire next_bit,output wire [27:0] result);
    wire [27:0] corrected;
    decimal_add3 d0(.digit(previous[3:0]),.corrected(corrected[3:0]));
    decimal_add3 d1(.digit(previous[7:4]),.corrected(corrected[7:4]));
    decimal_add3 d2(.digit(previous[11:8]),.corrected(corrected[11:8]));
    decimal_add3 d3(.digit(previous[15:12]),.corrected(corrected[15:12]));
    decimal_add3 d4(.digit(previous[19:16]),.corrected(corrected[19:16]));
    decimal_add3 d5(.digit(previous[23:20]),.corrected(corrected[23:20]));
    decimal_add3 d6(.digit(previous[27:24]),.corrected(corrected[27:24]));
    assign result = {corrected[26:0],next_bit};
endmodule
// Total add3 truth table; reachable BCD digits0..9 remain exact.
module decimal_add3(input wire [3:0] digit,output wire [3:0] corrected);
    wire [3:0] n;
    wire [15:0] m;
    not n0(n[0],digit[0]);
    not n1(n[1],digit[1]);
    not n2(n[2],digit[2]);
    not n3(n[3],digit[3]);
    and m0(m[0],n[0],n[1],n[2],n[3]);
    and m1(m[1],digit[0],n[1],n[2],n[3]);
    and m2(m[2],n[0],digit[1],n[2],n[3]);
    and m3(m[3],digit[0],digit[1],n[2],n[3]);
    and m4(m[4],n[0],n[1],digit[2],n[3]);
    and m5(m[5],digit[0],n[1],digit[2],n[3]);
    and m6(m[6],n[0],digit[1],digit[2],n[3]);
    and m7(m[7],digit[0],digit[1],digit[2],n[3]);
    and m8(m[8],n[0],n[1],n[2],digit[3]);
    and m9(m[9],digit[0],n[1],n[2],digit[3]);
    and m10(m[10],n[0],digit[1],n[2],digit[3]);
    and m11(m[11],digit[0],digit[1],n[2],digit[3]);
    and m12(m[12],n[0],n[1],digit[2],digit[3]);
    and m13(m[13],digit[0],n[1],digit[2],digit[3]);
    and m14(m[14],n[0],digit[1],digit[2],digit[3]);
    and m15(m[15],digit[0],digit[1],digit[2],digit[3]);
    or out0(corrected[0],m[1],m[3],m[6],m[8],m[10],m[12],m[14]);
    or out1(corrected[1],m[2],m[3],m[7],m[8],m[11],m[12],m[15]);
    or out2(corrected[2],m[4],m[9],m[10],m[11],m[12]);
    or out3(corrected[3],m[5],m[6],m[7],m[8],m[9],m[10],m[11],m[12]);
endmodule
module decimal_bcd_segments(input wire [3:0] digit,output wire [6:0] segments);
    wire [3:0] n;
    wire [9:0] m;
    not n0(n[0],digit[0]);
    not n1(n[1],digit[1]);
    not n2(n[2],digit[2]);
    not n3(n[3],digit[3]);
    and m0(m[0],n[0],n[1],n[2],n[3]);
    and m1(m[1],digit[0],n[1],n[2],n[3]);
    and m2(m[2],n[0],digit[1],n[2],n[3]);
    and m3(m[3],digit[0],digit[1],n[2],n[3]);
    and m4(m[4],n[0],n[1],digit[2],n[3]);
    and m5(m[5],digit[0],n[1],digit[2],n[3]);
    and m6(m[6],n[0],digit[1],digit[2],n[3]);
    and m7(m[7],digit[0],digit[1],digit[2],n[3]);
    and m8(m[8],n[0],n[1],n[2],digit[3]);
    and m9(m[9],digit[0],n[1],n[2],digit[3]);
    nor seg0(segments[0],m[0],m[2],m[3],m[5],m[6],m[7],m[8],m[9]);
    nor seg1(segments[1],m[0],m[1],m[2],m[3],m[4],m[7],m[8],m[9]);
    nor seg2(segments[2],m[0],m[1],m[3],m[4],m[5],m[6],m[7],m[8],m[9]);
    nor seg3(segments[3],m[0],m[2],m[3],m[5],m[6],m[8],m[9]);
    nor seg4(segments[4],m[0],m[2],m[6],m[8]);
    nor seg5(segments[5],m[0],m[4],m[5],m[6],m[8],m[9]);
    nor seg6(segments[6],m[2],m[3],m[4],m[5],m[6],m[8],m[9]);
endmodule
module decimal_position(input wire [3:0] digit,input wire show_digit,dash,output wire [6:0] segments);
    wire [6:0] decoded,active,visible;
    decimal_bcd_segments decoder(.digit(digit),.segments(decoded));
    not invert0(active[0],decoded[0]);
    and show0(visible[0],active[0],show_digit);
    not out0(segments[0],visible[0]);
    not invert1(active[1],decoded[1]);
    and show1(visible[1],active[1],show_digit);
    not out1(segments[1],visible[1]);
    not invert2(active[2],decoded[2]);
    and show2(visible[2],active[2],show_digit);
    not out2(segments[2],visible[2]);
    not invert3(active[3],decoded[3]);
    and show3(visible[3],active[3],show_digit);
    not out3(segments[3],visible[3]);
    not invert4(active[4],decoded[4]);
    and show4(visible[4],active[4],show_digit);
    not out4(segments[4],visible[4]);
    not invert5(active[5],decoded[5]);
    and show5(visible[5],active[5],show_digit);
    not out5(segments[5],visible[5]);
    not invert6(active[6],decoded[6]);
    and show6(visible[6],active[6],show_digit);
    nor out6(segments[6],visible[6],dash);
endmodule
